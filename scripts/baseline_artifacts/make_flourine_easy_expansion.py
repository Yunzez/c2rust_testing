    emit(
        "C2", "url_is_ssh_valid",
        ["#include <stdbool.h>", "#include <stdint.h>", "#include <stdlib.h>", "#include <string.h>"], [],
        ["bool url_is_ssh_valid(int8_t value[16]);"],
        c_fn + "\n\nbool url_is_ssh_valid(int8_t value[16]) { value[15] = 0; return url_is_ssh((char *)value); }",
        "use std::ffi::CStr;",
        r_fn,
        "#[no_mangle]\npub fn url_is_ssh_valid(value: &mut [i8; 16]) -> bool { value[15] = 0; url_is_ssh(value.as_mut_ptr()) }",
        {"c": str(c_path.relative_to(ROOT)), "rust": str(r_path.relative_to(ROOT))},
        "Force a 16-byte generated byte string to be NUL-terminated and call the exact target on both sides.",
    )


