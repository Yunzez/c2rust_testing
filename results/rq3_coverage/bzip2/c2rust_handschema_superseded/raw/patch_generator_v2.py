#!/usr/bin/env python3
"""RQ4 fix round 2 — complete the schema layer's output-buffer support in the scratchpad
copy of the harness generator.

Round 1 (patch recorded in raw/generator_rq4_fixes.diff) fixed two things a real library exposed:
canonical return types, and renaming C *globals* in the oracle.  This round fixes the input model,
which the first bzip2 campaign showed to be wrong on 6 of the 7 harnesses that ran:

  A. An output buffer whose capacity is passed BY POINTER had no representation.  `classify()`
     made bzip2's `char* dest` an `out_scalar` (a single stack byte) and `unsigned int* destLen`
     another `out_scalar` initialised to 0 -- so BZ2_bzBuffToBuffCompress was called with an
     output capacity of zero on every input and never wrote a byte.  `harness_schema.py` already
     names the role `output_buffer` with a `capacity_param`, but `items_from_schema` deliberately
     downgraded it to the `inout_buffer` decode ("the richer semantics are deferred").  This
     completes it: new param role `capacity_ptr`, new item role `out_buf_cap`.

  B. Input buffers were capped at 63 elements by a hardcoded `% 64` in the generated byte cursor,
     so bzip2 never saw a block big enough to leave the fallback sorter (`nblock < 10000`).  A
     schema may now set `max_len`, decoded with a new `take_rest_*` cursor method that consumes
     the remaining fuzz bytes up to that bound.

  C. Scalars were unbounded, so bzip2's own parameter validation rejected almost every input
     (blockSize100k must be 1..9, verbosity 0..4, workFactor 0..250).  `bounded_scalar` was
     already implemented end to end -- it was simply never emitted by inference.  Schemas now use
     it; no generator change was needed for this one.

  D. Schemas are per-program, keyed to one entry.  A library needs one per boundary, so
     `--schema PATH` selects an explicit schema file.

  E. With a large buffer decoded first, every scalar after it moves whenever the buffer length
     changes.  A schema may set `decode_scalars_first`, which emits scalar decodes before buffer
     decodes.  Call order is unaffected: decode order comes from `items`, ABI order from `abi`.

Nothing here changes the eligibility rule.
"""
import pathlib, re, sys

SCR = pathlib.Path("/tmp/claude-1000/-home-yunzez-c2rust-testing/"
                   "6278f822-c4c5-451c-94c6-d3a713132b29/scratchpad/rq4_cov/rq4_gen")


def patch_schema_module():
    p = SCR / "harness_schema.py"
    t = p.read_text()
    t = t.replace(
        '''ROLES = {"scalar", "input_buffer", "inout_buffer", "output_buffer", "out_scalar",''',
        '''ROLES = {"scalar", "input_buffer", "inout_buffer", "output_buffer", "out_scalar",
         "capacity_ptr",  # RQ4: in/out capacity passed BY POINTER, owned by an output_buffer''')
    t = t.replace(
        '''DECODES = {"scalar", "bounded_scalar", "vector", "derived_from_buffer", "out_scalar_zero",''',
        '''DECODES = {"scalar", "bounded_scalar", "vector", "derived_from_buffer", "out_scalar_zero",
           "capacity_ptr_inout",  # RQ4''')
    t = t.replace(
        '''    "length": "derived_from_buffer", "capacity": "derived_from_buffer",
}''',
        '''    "length": "derived_from_buffer", "capacity": "derived_from_buffer",
    "capacity_ptr": "capacity_ptr_inout",
}''')
    # a capacity_ptr param is a mutable pointer, like the other mut roles
    t = t.replace('''    mut_roles = ("output_buffer", "inout_buffer", "out_scalar")''',
                  '''    mut_roles = ("output_buffer", "inout_buffer", "out_scalar", "capacity_ptr")''')
    # an output_buffer must also say how big to allocate it
    t = t.replace(
        '''        if p.get("role") == "output_buffer" and "capacity_param" not in p:
            errs.append(f"{p['name']}: output_buffer missing capacity_param")''',
        '''        if p.get("role") == "output_buffer" and "capacity_param" not in p:
            errs.append(f"{p['name']}: output_buffer missing capacity_param")
        if p.get("role") == "output_buffer" and not isinstance(p.get("cap"), int):
            errs.append(f"{p['name']}: output_buffer needs an integer cap (allocation size)")
        if p.get("role") in ("input_buffer", "inout_buffer") and "max_len" in p \\
                and not isinstance(p["max_len"], int):
            errs.append(f"{p['name']}: max_len must be an int")''')
    p.write_text(t)
    print("harness_schema.py patched")


def patch_generator():
    p = SCR / "gen_diff_harness.py"
    t = p.read_text()

    # ---- capability stamp ----
    t = t.replace('GEN_VERSION = "0.5+rq4fix2026-09-03"  # scratchpad copy: canonical return type; C-global renaming',
                  'GEN_VERSION = "0.5+rq4fix2026-09-03b"  # + output_buffer/capacity_ptr, max_len, per-entry schema')
    t = t.replace('''    "input_struct_array", "inout_struct_array", "output_array",
)''',
                  '''    "input_struct_array", "inout_struct_array", "output_array",
    "output_buffer_with_capacity_ptr",   # RQ4
)''')

    # ---- items_from_schema: real output_buffer, max_len, scalars-first ----
    old = '''        elif role in ("inout_buffer", "output_buffer"):
            ln = p.get("length_param") or p.get("capacity_param")
            items.append({"kind": "ptr", "role": "io_buf", "name": p["name"],
                          "elem": p["elem"], "elem_w": p["elem_width"], "len_name": ln,
                          "len_rust": param_rust.get(ln) or "usize"})'''
    new = '''        elif role == "output_buffer":
            # RQ4: a real output buffer -- allocated to `cap`, with its capacity handed to the
            # callee. When the capacity param is itself a pointer (`capacity_ptr`) the callee both
            # READS it as the capacity and WRITES the produced length back, so it is an in/out
            # scalar seeded with the allocation size, and the observable output is the prefix
            # [0, written_length).
            cp = p["capacity_param"]
            if param_role.get(cp) == "capacity_ptr":
                items.append({"kind": "ptr", "role": "out_buf_cap", "name": p["name"],
                              "elem": p["elem"], "elem_w": p["elem_width"], "cap": p["cap"],
                              "cap_name": cp, "cap_rust": param_elem.get(cp) or "u32"})
            else:
                items.append({"kind": "ptr", "role": "io_buf", "name": p["name"],
                              "elem": p["elem"], "elem_w": p["elem_width"], "len_name": cp,
                              "len_rust": param_rust.get(cp) or "usize"})
        elif role == "inout_buffer":
            ln = p.get("length_param") or p.get("capacity_param")
            it = {"kind": "ptr", "role": "io_buf", "name": p["name"],
                  "elem": p["elem"], "elem_w": p["elem_width"], "len_name": ln,
                  "len_rust": param_rust.get(ln) or "usize"}
            if "max_len" in p:
                it["max_len"] = p["max_len"]
            items.append(it)'''
    assert old in t
    t = t.replace(old, new)

    old = '''        elif role == "input_buffer":
            items.append({"kind": "ptr", "role": "in_buf", "name": p["name"],
                          "elem": p["elem"], "elem_w": p["elem_width"], "len_name": p["length_param"],
                          "len_rust": param_rust.get(p["length_param"]) or "usize"})'''
    new = '''        elif role == "input_buffer":
            it = {"kind": "ptr", "role": "in_buf", "name": p["name"],
                  "elem": p["elem"], "elem_w": p["elem_width"], "len_name": p["length_param"],
                  "len_rust": param_rust.get(p["length_param"]) or "usize"}
            if "max_len" in p:
                it["max_len"] = p["max_len"]
            items.append(it)'''
    assert old in t
    t = t.replace(old, new)

    t = t.replace('''    param_rust = {p["name"]: p.get("rust") for p in schema["params"]}''',
                  '''    param_rust = {p["name"]: p.get("rust") for p in schema["params"]}
    param_role = {p["name"]: p.get("role") for p in schema["params"]}
    param_elem = {p["name"]: p.get("elem") for p in schema["params"]}''')

    t = t.replace('''        # length / capacity params are consumed by their owning buffer (not standalone items)
    return items''',
                  '''        # length / capacity / capacity_ptr params are consumed by their owning buffer
    if schema.get("decode_scalars_first"):
        # RQ4: decode every scalar before any buffer, so a scalar's byte offset does not move when
        # a (possibly megabyte-sized) buffer changes length. Call order is unaffected: the call is
        # built from `abi`, in strict declaration order.
        buf_roles = ("in_buf", "io_buf", "out_buf_cap", "in_str", "in_arr", "in_table",
                     "in_str_table", "in_struct_arr", "io_struct_arr")
        items.sort(key=lambda i: 1 if i["role"] in buf_roles else 0)
    return items''')

    # ---- decode + compare for out_buf_cap, and max_len for in/io buffers ----
    old = '''        elif it["role"] == "in_buf":
            decode.append(f"    let {n}_buf: Vec<{it['elem']}> = cur.take_vec_{it['elem']}();")
            decode.append(f"    let {it['len_name']} = {n}_buf.len(){_len_cast(it)};")
        elif it["role"] == "io_buf":
            decode.append(f"    let mut {n}_c: Vec<{it['elem']}> = cur.take_vec_{it['elem']}();")
            decode.append(f"    let {it['len_name']} = {n}_c.len(){_len_cast(it)};")
            decode.append(f"    let mut {n}_r = {n}_c.clone();")
            post.append(f'    if {n}_c != {n}_r {{ panic!("divergence: buffer {n}"); }}')'''
    new = '''        elif it["role"] == "in_buf":
            take = (f"cur.take_rest_{it['elem']}({it['max_len']})" if "max_len" in it
                    else f"cur.take_vec_{it['elem']}()")
            decode.append(f"    let {n}_buf: Vec<{it['elem']}> = {take};")
            decode.append(f"    let {it['len_name']} = {n}_buf.len(){_len_cast(it)};")
        elif it["role"] == "io_buf":
            take = (f"cur.take_rest_{it['elem']}({it['max_len']})" if "max_len" in it
                    else f"cur.take_vec_{it['elem']}()")
            decode.append(f"    let mut {n}_c: Vec<{it['elem']}> = {take};")
            decode.append(f"    let {it['len_name']} = {n}_c.len(){_len_cast(it)};")
            decode.append(f"    let mut {n}_r = {n}_c.clone();")
            post.append(f'    if {n}_c != {n}_r {{ panic!("divergence: buffer {n}"); }}')
        elif it["role"] == "out_buf_cap":
            # RQ4: output buffer whose capacity is passed by pointer. Both sides get their own
            # zeroed allocation of `cap` elements and their own capacity cell seeded with `cap`.
            # After the call the callee has overwritten the cell with the length it produced, so
            # the observable output is that length plus the prefix it names -- comparing the whole
            # allocation would compare bytes the callee never wrote.
            c, cn, cr = it["cap"], it["cap_name"], it["cap_rust"]
            decode.append(f"    let mut {n}_c: Vec<{it['elem']}> = vec![0 as {it['elem']}; {c}];")
            decode.append(f"    let mut {n}_r: Vec<{it['elem']}> = vec![0 as {it['elem']}; {c}];")
            decode.append(f"    let mut {cn}_c: {cr} = {c} as {cr};")
            decode.append(f"    let mut {cn}_r: {cr} = {c} as {cr};")
            post.append(f'    if {cn}_c != {cn}_r {{ panic!("divergence: written length {cn}"); }}')
            post.append(f"    {{ let _n = ({cn}_c as usize).min({c});")
            post.append(f'      if {n}_c[.._n] != {n}_r[.._n] {{ panic!("divergence: output buffer {n}"); }} }}')'''
    assert old in t
    t = t.replace(old, new)

    # ---- call + extern decl for capacity_ptr ----
    old = '''        elif role == "out_scalar":
            c_args.append(f"&mut {n}_c"); r_pairs.append((n, f"&mut {n}_r"))
            decl.append(f"{n}: *mut {p['elem']}")'''
    new = '''        elif role in ("out_scalar", "capacity_ptr"):
            c_args.append(f"&mut {n}_c"); r_pairs.append((n, f"&mut {n}_r"))
            decl.append(f"{n}: *mut {p['elem']}")'''
    assert old in t
    t = t.replace(old, new)

    # ---- byte cursor: take_rest_<ty>(max) ----
    rest = ('''        *[f"    fn take_rest_{t}(&mut self, max: usize) -> Vec<{t}> {{ let mut v = Vec::new(); "
          f"while self.p < self.d.len() && v.len() < max {{ v.push(self.take_{t}()); }} v }}"
          for t in ["u8", "i8", "u16", "i16", "u32", "i32", "u64", "i64"]],
''')
    old_cur = '''        *[f"    fn take_vec_{t}(&mut self) -> Vec<{t}> {{ let n = (self.byte() as usize) % 64; (0..n).map(|_| self.take_{t}()).collect() }}"
          for t in ["u8", "i8", "u16", "i16", "u32", "i32", "u64", "i64"]],
        "}",'''
    assert t.count(old_cur) == 2, f"expected the cursor block twice, found {t.count(old_cur)}"
    t = t.replace(old_cur, old_cur.replace('        "}",', rest + '        "}",'))

    # ---- --schema PATH ----
    t = t.replace('''def resolve(name: str, cc_dir: Path, entry: str, infer: bool = False, ignore_schema: bool = False):''',
                  '''def resolve(name: str, cc_dir: Path, entry: str, infer: bool = False, ignore_schema: bool = False,
            schema_path: Path | None = None):''')
    t = t.replace('''    schema_path = ROOT / "schemas" / f"{name}.json"
    if schema_path.exists():''',
                  '''    # RQ4: --schema selects an explicit file, because schemas/<program>.json is keyed to a
    # single entry and a library needs one schema per boundary.
    schema_path = Path(schema_path) if schema_path else (ROOT / "schemas" / f"{name}.json")
    if schema_path.exists():''')
    t = t.replace('''        if schema.get("program") != name:
            errs.append(f"schema program {schema.get('program')!r} != pair {name!r}")''',
                  '''        if schema.get("program") != name:
            errs.append(f"schema program {schema.get('program')!r} != pair {name!r}")''')
    t = t.replace('''    ap.add_argument("--ignore-schema", action="store_true",''',
                  '''    ap.add_argument("--schema", default=None,
                    help="explicit schema file (schemas/<program>.json is keyed to ONE entry; a "
                         "library needs one schema per boundary)")
    ap.add_argument("--ignore-schema", action="store_true",''')
    t = t.replace('''    params, ret, all_fns, items, abi = resolve(
        name, cc, args.entry, infer=args.infer_schema, ignore_schema=args.ignore_schema)''',
                  '''    params, ret, all_fns, items, abi = resolve(
        name, cc, args.entry, infer=args.infer_schema, ignore_schema=args.ignore_schema,
        schema_path=args.schema)''')

    p.write_text(t)
    print("gen_diff_harness.py patched")


if __name__ == "__main__":
    patch_schema_module()
    patch_generator()
