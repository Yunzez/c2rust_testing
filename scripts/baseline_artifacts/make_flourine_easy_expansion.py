def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def brace_item(text: str, marker: str) -> str:
    start = text.index(marker)
    brace = text.index("{", start)
    depth = 0
    for index in range(brace, len(text)):
        if text[index] == "{":
            depth += 1
        elif text[index] == "}":
            depth -= 1
            if depth == 0:
                return text[start : index + 1]
    raise ValueError(marker)


def emit(
    defect: str,
    target: str,
    includes: list[str],
    defines: list[str],
    declarations: list[str],
    c_code: str,
    rust_prelude: str,
    rust_exact: str,
    rust_wrapper: str,
    sources: dict[str, str],
    contract: str,
) -> None:
    out = ROOT / f"results/baseline_artifacts/adapters/flourine/{defect}"
    input_dir = out / "input"
    input_dir.mkdir(parents=True, exist_ok=True)
    json_path = input_dir / f"{target}.json"
    rust_path = input_dir / f"{target}.rs"
    raw_path = input_dir / f"{target}_raw.inc"
    json_path.write_text(
        json.dumps(
            {
                "Includes": includes,
                "Defines": defines,
                "TypeDefs": [],
                "Globals": [],
                "Structs": [],
                "Function Declarations": declarations,
                "Function Implementations": [c_code],
                "Enums": [],
            },
            indent=2,
        )
        + "\n"
    )
    raw_path.write_text(rust_exact.rstrip() + "\n")
    rust_path.write_text(
        rust_prelude.rstrip()
        + f'\n\ninclude!["/input/{raw_path.name}"];\n\n'
        + rust_wrapper.rstrip()
        + "\n"
    )
    metadata = {
        "schema_version": 1,
        "defect": defect,
        "baseline": "flourine",
        "target": target,
        "adapter_kind": "documented_per_function_json_with_safe_fixed_shape_wrapper",
        "semantic_rewrite": False,
        "known_witness_encoded": False,
        "sources": sources,
        "wrapper_contract": contract,
        "input_sha256": {
            path.name: sha256(path) for path in [json_path, rust_path, raw_path]
        },
    }
    (out / "adapter.json").write_text(json.dumps(metadata, indent=2) + "\n")


def make_c2() -> None:
    c_path = ROOT / "benchmark/pairs/rq4/urlparser_c2saferrust/source/url.h"
    r_path = ROOT / "benchmark/pairs/rq4/urlparser_c2saferrust/translated/urlparser_c2saferrust.rs"
    c_fn = brace_item(c_path.read_text(), "bool\nurl_is_ssh (char *str) {")
